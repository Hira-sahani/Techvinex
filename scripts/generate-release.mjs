#!/usr/bin/env node
// Generates a stable release identifier shared by the frontend bundle and
// every edge function. Runs at build start (via the vite plugin) and is
// safe to invoke manually too.
//
// Format: techvinex@<short-sha>[-dirty]   (git available)
//         techvinex@ts-<unix-ms>          (git unavailable)
//
// Writes two files containing IDENTICAL release strings so events from the
// browser and Deno edge runtime correlate in Sentry:
//   - src/generated/release.ts            (imported by src/lib/sentry.ts)
//   - supabase/functions/_shared/release.ts (imported by edge sentry helper)
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function sh(cmd) {
  try { return execSync(cmd, { cwd: ROOT, stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); }
  catch { return ""; }
}

function computeRelease() {
  // Allow CI / Lovable to override via env (highest precedence).
  if (process.env.SENTRY_RELEASE) return process.env.SENTRY_RELEASE;

  const sha = sh("git rev-parse --short=10 HEAD");
  if (sha) {
    const dirty = sh("git status --porcelain") ? "-dirty" : "";
    return `techvinex@${sha}${dirty}`;
  }
  return `techvinex@ts-${Date.now()}`;
}

const RELEASE = computeRelease();
// Default to "production" so any deployed bundle / edge function reports as
// production unless explicitly overridden. Local dev never reaches Sentry
// because src/lib/sentry.ts short-circuits when import.meta.env.DEV is true.
// Always default to "production" — Sentry never receives events from
// local dev (src/lib/sentry.ts short-circuits when import.meta.env.DEV),
// so the only events reaching Sentry are from deployed bundles / edge
// functions, which should be tagged production unless SENTRY_ENVIRONMENT
// explicitly overrides (e.g. staging/canary).
const ENVIRONMENT = process.env.SENTRY_ENVIRONMENT || "production";

const banner = `// AUTO-GENERATED by scripts/generate-release.mjs — DO NOT EDIT.
// Regenerated at every build. Frontend and edge functions import this so
// Sentry events share the same release tag.
`;

const tsContent = `${banner}
export const RELEASE = ${JSON.stringify(RELEASE)};
export const ENVIRONMENT = ${JSON.stringify(ENVIRONMENT)};
`;

function writeIfChanged(path, content) {
  const abs = resolve(ROOT, path);
  mkdirSync(dirname(abs), { recursive: true });
  if (existsSync(abs)) {
    try {
      if (readFileSync(abs, "utf8") === content) return false;
    } catch { /* fall through */ }
  }
  writeFileSync(abs, content);
  return true;
}

const wroteFe = writeIfChanged("src/generated/release.ts", tsContent);
const wroteEdge = writeIfChanged("supabase/functions/_shared/release.ts", tsContent);

if (process.env.GENERATE_RELEASE_VERBOSE) {
  // eslint-disable-next-line no-console
  console.log(`[release] ${RELEASE} (${ENVIRONMENT}) frontend=${wroteFe ? "wrote" : "cached"} edge=${wroteEdge ? "wrote" : "cached"}`);
}

export { RELEASE, ENVIRONMENT };
